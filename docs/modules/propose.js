/* FreeLattice — Propose (window.FLPropose)
 * ──────────────────────────────────────────────────────────────────
 * Ship 4 Phase 1 (v5.42.0, 2026-06-09).
 *
 * ─── THE STRUCTURAL COMMIT GATE ───
 *
 * approveDraft(id) is the ONLY function in this codebase that calls
 * the bridge's git/commit endpoint with AI-generated content, and it
 * cannot be invoked except by an explicit click on a button whose
 * `disabled` attribute is controlled by `smokeStatus === 'passed'`.
 *
 * That click is the gate. That click is the human signature on the
 * change. There is no auto-commit path at any trust tier — not even
 * Radiant. The trust gate happened at the consent layer; the commit
 * gate is structural.
 *
 * ─── THE LEDGER PRIVACY LOCK ───
 *
 * fl_proposalLedger rows shape: { ts, action, draftId, path,
 * sourceRoom, status }. The diff is NOT in the ledger. The reason
 * is NOT in the ledger. Both live in fl_proposalDrafts, a separate
 * larger transient store. Same separation pattern as Ship 3's
 * search ledger (which doesn't carry the query).
 *
 * Patterns exercised (UPDATE.md):
 *   §1  Sentinel pattern ([FL_PROPOSE:])
 *   §2  Trust-aware phi-branching (via FLToolConsent)
 *   §3  Audit ledger (privacy-locked, no diff/reason)
 *   §4  IIFE scoping + explicit window exposure
 *   §8  Quiet Room exclusion at every entry point
 *   §9  Snowflake — same generating rule as repo-context + web-tool,
 *       larger scale (write instead of read)
 *
 * See docs/library/SHIP_4_BRIEF.md for Opus's full brief and
 * docs/library/PROPOSE_DISCIPLINE.md for the human-readable contract.
 */
(function () {
  'use strict';

  var LEDGER_KEY = 'fl_proposalLedger';
  var DRAFTS_KEY = 'fl_proposalDrafts';
  var LEDGER_CAP = 200;
  var DRAFTS_CAP = 50;
  var DIFF_LENGTH_CAP = 50000;
  var PATH_LENGTH_CAP = 300;
  var REASON_LENGTH_CAP = 500;

  var QUIET_ROOMS = ['quiet', 'quiet-room', 'sanctuary'];

  // Codebase-specific sensitive paths — verified during Ship 4 prep:
  //   .git/            — repo metadata
  //   node_modules/    — installed dependencies
  //   .env (and .env.*)— environment secrets
  //   .ssh/            — keys
  //   wrangler.toml    — Cloudflare worker secrets binding
  //   package-lock.json— deterministic install file (never AI-edited)
  //   worker/          — entire worker dir is secrets-adjacent
  //   scripts/bump-version.sh — build infrastructure (humans only)
  //   FreeLattice_Session_Primer.md — auto-generated by post-commit hook
  var FORBIDDEN_PATH_FRAGMENTS = [
    '.git/',
    'node_modules/',
    '.env',
    '.ssh/',
    'wrangler.toml',
    'package-lock.json',
    'worker/',
    'scripts/bump-version.sh',
    'FreeLattice_Session_Primer.md'
  ];

  // ── Utilities ────────────────────────────────────────────────────
  function getCurrentTab() {
    try {
      var btn = document.querySelector('.tab-btn.active, [data-tab].active');
      return (btn && btn.dataset && btn.dataset.tab) || null;
    } catch (e) { return null; }
  }

  function isQuietRoom(roomId) {
    var r = roomId || getCurrentTab() || '';
    return QUIET_ROOMS.indexOf(String(r).toLowerCase()) !== -1;
  }

  // ── Path safety — the hard line ──────────────────────────────────
  function isPathSafe(path) {
    if (!path || typeof path !== 'string') return false;
    if (path.length > PATH_LENGTH_CAP) return false;
    if (path.indexOf('..') !== -1) return false;        // traversal
    if (path.indexOf('\0') !== -1) return false;        // null byte
    if (/^[\/\\]/.test(path)) return false;             // absolute /
    if (/^[a-zA-Z]:[\\/]/.test(path)) return false;     // absolute C:\

    // Forbidden fragments — match at start or after a /.
    for (var i = 0; i < FORBIDDEN_PATH_FRAGMENTS.length; i++) {
      var frag = FORBIDDEN_PATH_FRAGMENTS[i];
      if (path.indexOf(frag) === 0) return false;
      if (path.indexOf('/' + frag) !== -1) return false;
    }

    return true;
  }

  // ── Sentinel parsing ─────────────────────────────────────────────
  // The sentinel format Opus specified:
  //
  //   [FL_PROPOSE:
  //     path: <file path>
  //     reason: <one-line commit message>
  //     diff:
  //       <unified diff>
  //   ]
  //
  // The closing `]` MUST be on its own line so the parser knows where
  // the diff ends. The diff itself may contain `]` characters; we
  // anchor on `\n]` at end of input or before a blank.
  var SENTINEL_RE = /\[FL_PROPOSE:([\s\S]*?)\n\]/;
  var SENTINEL_RE_G = /\[FL_PROPOSE:[\s\S]*?\n\]/g;

  function interceptSentinel(aiText) {
    if (typeof aiText !== 'string') {
      return { visibleText: aiText, action: null };
    }
    var match = aiText.match(SENTINEL_RE);
    if (!match) return { visibleText: aiText, action: null };

    var body = match[1];
    var parsed = parseProposalBody(body);
    var visibleText = aiText.replace(SENTINEL_RE_G, '').trim();

    if (!parsed) {
      // Strip the sentinel from visible text either way; surface the
      // malformed status so the chat pipeline can render a graceful
      // message asking the AI to try again.
      return {
        visibleText: visibleText,
        action: { type: 'propose_malformed' }
      };
    }

    return {
      visibleText: visibleText,
      action: {
        type: 'propose',
        path: parsed.path,
        reason: parsed.reason,
        diff: parsed.diff
      }
    };
  }

  function parseProposalBody(body) {
    if (!body || typeof body !== 'string') return null;
    var pathMatch = body.match(/path:\s*([^\n]+)/);
    var reasonMatch = body.match(/reason:\s*([^\n]+)/);
    var diffStart = body.indexOf('diff:');
    if (!pathMatch || !reasonMatch || diffStart === -1) return null;

    var path = pathMatch[1].trim();
    var reason = reasonMatch[1].trim().slice(0, REASON_LENGTH_CAP);
    var diff = body.slice(diffStart + 'diff:'.length).trim();

    if (!isPathSafe(path)) return null;
    if (!diff || diff.length === 0) return null;
    if (diff.length > DIFF_LENGTH_CAP) return null;

    return { path: path, reason: reason, diff: diff };
  }

  // ── Ledger (privacy-locked — no diff, no reason) ─────────────────
  function appendLedger(row) {
    try {
      var raw = localStorage.getItem(LEDGER_KEY);
      var rows = raw ? JSON.parse(raw) : [];
      if (!Array.isArray(rows)) rows = [];
      // STRICT row shape — six fields only. NEVER diff or reason or content.
      var sanitized = {
        ts: Date.now(),
        action: row.action || 'unknown',
        draftId: row.draftId || null,
        path: row.path || null,
        sourceRoom: row.sourceRoom || null,
        status: row.status || null
      };
      rows.push(sanitized);
      if (rows.length > LEDGER_CAP) rows = rows.slice(-LEDGER_CAP);
      localStorage.setItem(LEDGER_KEY, JSON.stringify(rows));
    } catch (e) { /* ledger failure must not break the feature */ }
  }

  // ── Drafts store ─────────────────────────────────────────────────
  function loadDrafts() {
    try {
      var raw = localStorage.getItem(DRAFTS_KEY);
      var parsed = raw ? JSON.parse(raw) : [];
      return Array.isArray(parsed) ? parsed : [];
    } catch (e) { return []; }
  }

  function saveDrafts(drafts) {
    try {
      var capped = drafts.length > DRAFTS_CAP ? drafts.slice(-DRAFTS_CAP) : drafts;
      localStorage.setItem(DRAFTS_KEY, JSON.stringify(capped));
      return true;
    } catch (e) { return false; }
  }

  function createDraft(action, context) {
    if (!action || action.type !== 'propose') return null;
    if (isQuietRoom(context && context.sourceRoom)) return null;
    if (!isPathSafe(action.path)) return null;

    var id = 'draft_' + Date.now() + '_' + Math.random().toString(36).slice(2, 8);
    var sourceRoom = (context && context.sourceRoom) || getCurrentTab() || 'chat';
    var draft = {
      id: id,
      ts: Date.now(),
      path: action.path,
      reason: action.reason || '',
      diff: action.diff || '',
      sourceRoom: sourceRoom,
      status: 'pending',
      smokeStatus: 'not-run',
      smokeOutput: '',
      reviewerNotes: '',
      updatedAt: null,
      committedSha: null
    };

    var drafts = loadDrafts();
    drafts.push(draft);
    if (!saveDrafts(drafts)) return null;

    appendLedger({
      action: 'created',
      draftId: id,
      path: draft.path,
      sourceRoom: sourceRoom,
      status: 'pending'
    });

    return draft;
  }

  function listDrafts() { return loadDrafts(); }

  function getDraft(id) {
    var all = loadDrafts();
    for (var i = 0; i < all.length; i++) {
      if (all[i].id === id) return all[i];
    }
    return null;
  }

  function updateDraftStatus(id, status, fields) {
    fields = fields || {};
    var all = loadDrafts();
    var found = false;
    for (var i = 0; i < all.length; i++) {
      if (all[i].id !== id) continue;
      found = true;
      all[i].status = status;
      all[i].updatedAt = Date.now();
      if (fields.reviewerNotes != null) all[i].reviewerNotes = String(fields.reviewerNotes).slice(0, 1000);
      if (fields.smokeStatus != null) all[i].smokeStatus = fields.smokeStatus;
      if (fields.smokeOutput != null) all[i].smokeOutput = String(fields.smokeOutput).slice(0, 50000);
      if (fields.committedSha != null) all[i].committedSha = fields.committedSha;
      break;
    }
    if (!found) return false;
    if (!saveDrafts(all)) return false;
    appendLedger({
      action: 'status-change',
      draftId: id,
      path: all.filter(function (d) { return d.id === id; })[0].path,
      status: status
    });
    return true;
  }

  function pendingCount() {
    return loadDrafts().filter(function (d) { return d.status === 'pending'; }).length;
  }

  // ── Unified-diff applier (minimal, strict) ───────────────────────
  // Parses hunks delimited by `@@ ... @@`. For each hunk, builds the
  // exact "before" text from context + minus lines, and "after" text
  // from context + plus lines. Then does a literal replace in the
  // original content. If any hunk's "before" text isn't found
  // exactly, the apply fails and the caller surfaces a graceful
  // error → draft moves to awaiting-revision.
  //
  // STRICT BY DESIGN: no fuzzy matching. The discipline reason —
  // if the AI's diff doesn't match the current file context exactly,
  // either the file changed or the AI misread it. Either way, the
  // human should see the divergence and ask for a revision.
  function applyUnifiedDiff(original, diffText) {
    if (typeof original !== 'string') throw new Error('original not a string');
    if (typeof diffText !== 'string') throw new Error('diff not a string');

    var lines = diffText.split('\n');
    var hunks = [];
    var current = null;

    for (var i = 0; i < lines.length; i++) {
      var line = lines[i];
      if (/^@@.*@@/.test(line)) {
        if (current) hunks.push(current);
        current = { lines: [] };
      } else if (current) {
        if (line.length === 0) {
          current.lines.push(' ');  // blank context line
        } else if (line.charAt(0) === ' ' || line.charAt(0) === '+' || line.charAt(0) === '-') {
          current.lines.push(line);
        }
        // Lines that don't start with + - or space (file headers, ---/+++ etc.) are ignored.
      }
      // Lines before the first @@ are ignored (diff headers).
    }
    if (current) hunks.push(current);

    if (hunks.length === 0) throw new Error('No hunks found in diff');

    var result = original;
    for (var h = 0; h < hunks.length; h++) {
      var hunk = hunks[h];
      var before = [];
      var after = [];
      for (var j = 0; j < hunk.lines.length; j++) {
        var l = hunk.lines[j];
        var marker = l.charAt(0);
        var body = l.slice(1);
        if (marker === ' ') { before.push(body); after.push(body); }
        else if (marker === '-') { before.push(body); }
        else if (marker === '+') { after.push(body); }
      }
      var beforeText = before.join('\n');
      var afterText = after.join('\n');
      if (beforeText === afterText) continue;  // no-op hunk
      if (!beforeText) throw new Error('Hunk ' + (h + 1) + ' has no before-text to anchor on');
      var idx = result.indexOf(beforeText);
      if (idx === -1) {
        throw new Error('Hunk ' + (h + 1) + ' context not found in current file. The file may have changed since the AI read it. Ask for a revision.');
      }
      // Replace only the FIRST occurrence to keep the apply deterministic.
      result = result.slice(0, idx) + afterText + result.slice(idx + beforeText.length);
    }
    return result;
  }

  // ── Bridge integration (delegated wrappers) ─────────────────────
  // approveDraft and runSmokeOnDraft are the only functions in this
  // module that talk to the local Workshop bridge. Both are gated
  // on draft state and one (approve) is also gated on smokeStatus.
  var BRIDGE = 'http://localhost:3141';

  function readFileFromBridge(path) {
    return fetch(BRIDGE + '/code/read?path=' + encodeURIComponent(path))
      .then(function (r) { return r.json(); });
  }

  function writeFileToBridge(path, content) {
    return fetch(BRIDGE + '/code/write', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ path: path, content: content })
    }).then(function (r) { return r.json(); });
  }

  function commitViaBridge(message) {
    return fetch(BRIDGE + '/code/git/commit', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ message: message })
    }).then(function (r) { return r.json(); });
  }

  function runSmokeViaBridge() {
    return fetch(BRIDGE + '/test/run', {
      signal: typeof AbortSignal !== 'undefined' && AbortSignal.timeout ? AbortSignal.timeout(120000) : undefined
    }).then(function (r) { return r.json(); });
  }

  function runSmokeOnDraft(id) {
    var draft = getDraft(id);
    if (!draft) return Promise.resolve({ ok: false, reason: 'no-draft' });
    if (draft.status !== 'pending') return Promise.resolve({ ok: false, reason: 'not-pending' });
    return runSmokeViaBridge().then(function (result) {
      // Bridge shape varies; assume {ok, passed, failed, output} or similar.
      var passed = result && (result.ok === true || result.passed === true ||
                              (typeof result.failed === 'number' && result.failed === 0));
      var failedCount = result && typeof result.failed === 'number' ? result.failed : (passed ? 0 : null);
      var output = result && (result.output || result.text || JSON.stringify(result));
      updateDraftStatus(id, 'pending', {
        smokeStatus: passed ? 'passed' : 'failed',
        smokeOutput: output
      });
      return { ok: true, passed: passed, failed: failedCount, output: output };
    }).catch(function (e) {
      updateDraftStatus(id, 'pending', {
        smokeStatus: 'failed',
        smokeOutput: 'Smoke runner unreachable: ' + (e && e.message || 'unknown error')
      });
      return { ok: false, reason: 'bridge-error', error: e && e.message };
    });
  }

  // ── THE STRUCTURAL COMMIT GATE ───────────────────────────────────
  // approveDraft is the ONLY function in the codebase that calls
  // commitViaBridge with AI-originated content. Three internal gates:
  //   1. Draft must be 'pending'.
  //   2. smokeStatus MUST be 'passed'. No override. No force.
  //   3. Path must STILL be safe (re-verified at commit time in case
  //      anything in the codebase changed between draft creation
  //      and approval).
  function approveDraft(id) {
    var draft = getDraft(id);
    if (!draft) return Promise.resolve({ ok: false, reason: 'no-draft' });
    if (draft.status !== 'pending') return Promise.resolve({ ok: false, reason: 'not-pending' });
    if (draft.smokeStatus !== 'passed') return Promise.resolve({ ok: false, reason: 'smoke-not-passed' });
    if (!isPathSafe(draft.path)) return Promise.resolve({ ok: false, reason: 'path-unsafe' });

    // Step 1: read current file.
    return readFileFromBridge(draft.path).then(function (readResult) {
      if (!readResult || readResult.error || typeof readResult.content !== 'string') {
        return { ok: false, reason: 'read-failed', detail: readResult && readResult.error };
      }

      // Step 2: apply the diff. Strict — throws on context mismatch.
      var newContent;
      try {
        newContent = applyUnifiedDiff(readResult.content, draft.diff);
      } catch (e) {
        return { ok: false, reason: 'diff-apply-failed', detail: e && e.message };
      }

      // Step 3: write the new content.
      return writeFileToBridge(draft.path, newContent).then(function (writeResult) {
        if (!writeResult || writeResult.error) {
          return { ok: false, reason: 'write-failed', detail: writeResult && writeResult.error };
        }

        // Step 4: commit. AI-content commits are tagged so audit/proof
        // can trace which commits came through this gate.
        var msg = draft.reason || ('AI proposal: ' + draft.path);
        msg += '\n\n[FL-Propose] draft=' + draft.id + ' path=' + draft.path;
        return commitViaBridge(msg).then(function (commitResult) {
          if (!commitResult || commitResult.error) {
            return { ok: false, reason: 'commit-failed', detail: commitResult && commitResult.error };
          }
          var sha = commitResult.sha || commitResult.commit || null;
          updateDraftStatus(id, 'committed', { committedSha: sha });
          return { ok: true, sha: sha };
        });
      });
    });
  }

  function reviseDraft(id, reviewerNotes) {
    var draft = getDraft(id);
    if (!draft) return false;
    if (draft.status !== 'pending') return false;
    var ok = updateDraftStatus(id, 'awaiting-revision', { reviewerNotes: reviewerNotes || '' });
    if (ok && reviewerNotes && window.FLFocus && typeof window.FLFocus.setFocus === 'function') {
      // Carry the notes back to chat so the AI sees them on the
      // next turn. Same handoff pattern Ship 2 ships for cross-room.
      try {
        window.FLFocus.setFocus(
          draft.sourceRoom || 'chat',
          'Revising proposed change to ' + draft.path + ': ' + reviewerNotes,
          true
        );
      } catch (e) {}
    }
    return ok;
  }

  function rejectDraft(id, reviewerNotes) {
    if (!reviewerNotes || !String(reviewerNotes).trim()) return false;
    return updateDraftStatus(id, 'rejected', { reviewerNotes: reviewerNotes });
  }

  // ── Module availability ─────────────────────────────────────────
  // Requires the local Workshop bridge to be reachable. We do NOT
  // ping the bridge on every isAvailable() call (would be slow);
  // we trust the Workshop module's existing checkBridge() flow.
  function isAvailable() {
    if (isQuietRoom()) return false;
    if (typeof window === 'undefined') return false;
    // Workshop must be loaded for the review surface to exist.
    return !!(window.Workshop || window.FLWorkshop);
  }

  // ── Public API ──────────────────────────────────────────────────
  var api = {
    interceptSentinel: interceptSentinel,
    parseProposalBody: parseProposalBody,
    isPathSafe: isPathSafe,
    createDraft: createDraft,
    listDrafts: listDrafts,
    getDraft: getDraft,
    updateDraftStatus: updateDraftStatus,
    pendingCount: pendingCount,
    runSmokeOnDraft: runSmokeOnDraft,
    approveDraft: approveDraft,
    reviseDraft: reviseDraft,
    rejectDraft: rejectDraft,
    applyUnifiedDiff: applyUnifiedDiff,
    isQuietRoom: isQuietRoom,
    isAvailable: isAvailable,
    // Exposed for tests + audit page.
    _ledgerKey: LEDGER_KEY,
    _draftsKey: DRAFTS_KEY,
    _ledgerCap: LEDGER_CAP,
    _draftsCap: DRAFTS_CAP,
    _diffCap: DIFF_LENGTH_CAP,
    _forbiddenPathFragments: FORBIDDEN_PATH_FRAGMENTS,
    _phase: '4.0'
  };

  window.FreeLatticeModules = window.FreeLatticeModules || {};
  window.FreeLatticeModules.Propose = api;
  window.FLPropose = api;
})();
